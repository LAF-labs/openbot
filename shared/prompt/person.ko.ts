/**
 * 사장님이 어디에 있고 사장님의 시계가 몇 시인지 — 프롬프트의 문맥 층, 한두 줄.
 *
 * 왜 있는가. 오늘 날씨를 묻자 봇이 네이버를 검색하고 네이버가 짐작한 제주시를 "사장님 위치"라고
 * 답했다(2026-09-24 실측). 네이버는 요청이 온 주소로 위치를 짐작했고, 그 요청은 클라우드 VM에서
 * 도는 봇의 브라우저가 보낸 것이었다. 봇의 컴퓨터가 있는 곳은 사장님이 있는 곳이 아니다 — 그래서
 * 사장님의 시간대와 위치를 봇에게 직접 말해 주고, 사이트가 알아서 보여 주는 위치를 믿지 말라고
 * 적는다.
 *
 * 위치는 세 군데에서, 이 순서로 온다(주인, 2026-10-05: "지역과 날짜는 기본값 실제 위치 데이터,
 * fallback은 서울, 유저가 특정 위치를 말해주면 저장"): 이 사람이 말한 곳(내 정보 화면에 적었거나
 * 대화에서 말해서 봇이 저장한 곳), 없으면 이 사람이 허락해서 받은 기기의 대략적인 좌표(소수 둘째
 * 자리), 그것도 없으면 서울. 날씨 도구도 같은 순서로 읽는다(`kma-weather-rest.ts`, `whereOf`).
 *
 * 그 전까지는 둘 다 없으면 "먼저 한 번 여쭤보고"였다. 기준으로 삼는 제품은 위치를 모르는 사람이
 * "오늘 날씨 어때?"라고 물으면 묻지 않고 서울로 답했고, 우리는 "어느 동네 기준으로 알려드릴까요?"가
 * 첫 답이었다(여섯 번 중 여섯 번, `weather-with-no-place-is-seouls`). 이제 묻지 않고 서울 기준으로
 * 답하되 서울 기준이라고 말한다 — 그 한마디가 이 사람이 바로잡을 수 있는 유일한 손잡이다.
 *
 * 날짜와 시간대 줄은 맥락 층의 시계 줄(`context.ko.ts`의 `clockText`)이 맡고, 시각은 `now` 툴이
 * 맡는다. 여기서는 가게 줄 뒤에 서는 위치 줄만 만든다.
 *
 * 날씨만은 이제 검색이 아니다(2026-10-02). 기상청 키가 있는 배포의 봇은 `get_weather`를 갖고
 * (`server/src/plugins/kma-weather-rest.ts`), 인자 없이 부르면 여기 적힌 바로 그 위치의 날씨가 온다.
 * 이 줄은 그 전까지 날씨를 네이버 검색의 예로 들었고, 도구를 쥔 봇은 그 예를 따랐다 — 재 보니 세 번
 * 중 세 번 웹 검색을 부르고 네이버를 열었다(`WEATHER_BY_TOOL`). 그래서 날씨는 도구로 가라고 먼저
 * 말하고, 검색 길은 도구가 없는 배포와 날씨 아닌 일(가까운 곳)을 위해 남긴다.
 */
import type { Coordinates } from "../whereabouts";
import type { PromptMode } from "./index";

/**
 * 이 실행의 사장님. 모든 칸이 선택이다 — 없는 칸은 "모른다"이지 "기본값"이 아니다.
 *
 * `timeZone`은 사장님의 것일 때만 온다: 대화면 그 기기가 방금 보낸 것, 루틴이면 마지막 세션이
 * 저장해 둔 것. 둘 다 없으면 비어 있고, 날짜와 `now`는 배포의 시간대(`BOT_TIME_ZONE`, 기본 서울)로 읽힌다.
 */
export type PromptPerson = {
  timeZone?: string;
  locale?: string;
  place?: string;
  coordinates?: Coordinates;
  /**
   * 기기 좌표가 놓인 곳의 이름("서울특별시 강남구·서초구") — 서버가 기상청 지점표에서 읽어 붙인다
   * (`server/src/agents/person-context.ts`). 말한 곳이 없고 좌표만 있을 때, 그리고 표가 그 칸의
   * 이름을 알 때만 온다.
   *
   * 왜 있는가. 좌표만 가진 봇에게 "근처 약국 알려줘"라고 하자, 다섯 번 중 세 번은 숫자를 보고
   * 스스로 "강남역 근처로 보여서"라고 짐작해 그 이름으로 찾았고 두 번은 동네를 되물었다
   * (2026-10-05, `nearby-with-device-coordinates-does-not-ask`). 위도·경도는 검색어가 되지 못한다.
   * 날씨 도구가 좌표에 답할 때 붙여 주는 바로 그 이름을 여기에도 준다 — 짐작이 아니라 표에서.
   */
  near?: string;
};

/** 사이트가 짐작한 위치를 사장님 위치로 옮기지 않는다 — 이 파일이 생긴 실패 그 자체. */
const NOT_THE_SITES_GUESS =
  "사이트가 알아서 보여 주는 위치(현위치 같은)는 네 컴퓨터가 있는 곳이지 이 사람의 위치가 아니다.";

/**
 * 날씨는 도구로. "있으면"이라고 적는 까닭: 이 줄은 키가 없는 배포에서도 같은 글이고(프롬프트는 어떤
 * 도구가 실렸는지 모른 채 만들어진다), 없는 도구를 부르라는 문장은 지어낸 호출이 된다.
 *
 * 재서 적는다(2026-10-02, muse-spark, `weather-from-the-agency` 세 번씩). 도구의 설명은 처음부터
 * "날씨는 검색하거나 브라우저로 찾지 말고 이것으로 답한다"였지만, 이 줄이 네이버 검색을 날씨의 예로
 * 들던 동안에는 세 번 다 웹 검색 → 네이버였다. 도구 설명 한 줄은 프롬프트의 구체적인 예를 이기지
 * 못한다.
 */
const WEATHER_BY_TOOL =
  "날씨는 get_weather 도구가 있으면 검색하거나 브라우저로 찾지 말고 그것으로 답한다";

/**
 * 말하면 저장한다, 묻는 것만으로는 저장하지 않는다 — 대화에서만(루틴에는 말하는 사람이 없다).
 *
 * 저장하는 것은 `remember`의 `place`가 뜻하는 바로 그것이다(`shared/tools/self.ts`: "가게나 주로
 * 지내는 곳"): 사는 곳, 일하는 곳, 주로 지내는 곳 — 그리고 그것이 바뀌었다는 말("이사했어, 이제
 * 수원이야"). 저장된 곳이 있어도, 기기 좌표가 있어도 같은 규칙이고, 저장된 말이 기기 좌표보다 먼저
 * 읽힌다.
 *
 * 저장하지 않는 것을 적어 두는 까닭. 첫 글은 "사는·일하는·지금 있는 곳"이었다. "지금 부산 출장 와
 * 있어"는 지금 있는 곳이라 그 글대로면 저장되고, 저장된 곳은 통째로 바뀌므로 집이 부산으로
 * 덮이고 기기 좌표도 같이 지워진다 — 다음 주의 "오늘 날씨 어때?"가 부산 날씨가 된다(PR 91 리뷰).
 * 그래서 저장하는 곳을 하나로 못 박고, 그 밖의 곳은 저장하지 않고 그때만 쓴다고 적는다.
 *
 * 저장하지 않는 곳을 하나씩 세지는 않는다. 잠깐 있는 곳(출장·여행), 남의 곳, 예전에 살던 곳,
 * 질문의 대상일 뿐인 곳을 목록으로 적어 두었었는데, 그 넷은 목록이 있든 없든 한 번도 저장되지
 * 않았다(어느 글에서나 여섯 번 중 여섯 번, `docs/laf/eval-pack.md`) — 매 턴 앞에 서는 쉰일곱 자가
 * 아무 일도 하지 않고 있었다.
 *
 * 붙여 넣은 글만은 풀어 적는다. 글 속의 "저는 대전에 살고"는 일인칭이지만 이 사람의 말이 아니다.
 * 첫 글에서는 여섯 번 중 세 번 "대전 유성구"가 저장됐고("사장님은 대전에 살며…"), 목록에 "붙여
 * 넣은 글 속의 곳"이라고만 넣은 둘째 글에서도 한 번 저장됐다. 예문까지 적은 뒤로는 저장되지
 * 않았다(`a-place-in-pasted-text-is-not-saved`). "너에게 … 알려 주거나"도 같은 까닭이다: 이
 * 사람이 봇에게 한 말만.
 *
 * 매 턴 앞에 서는 글이다. 예는 하나씩만.
 */
const SAVE_WHAT_THEY_SAY =
  "이 사람이 너에게 사는 곳·일하는 곳·주로 지내는 곳을 알려 주거나 옮겼다고 하면('나 춘천 살아') 묻지 않았어도 시·구까지 remember의 place로 저장한다. 그 밖의 곳은 저장하지 않고 그때만 쓴다. 요약·번역하라고 붙여 넣은 글 속의 곳도 그렇다 — 그 글이 '저는 대전에 살고'라고 해도 이 사람이 알려 준 것이 아니다.";

/**
 * 서울은 지역이 답하는 것에만. 이 사람 주변을 알아야 하는 일은 묻는다.
 *
 * 주인의 기본값(실제 위치, 없으면 서울, 먼저 묻지 않는다)은 날씨·날짜처럼 어느 지역인지만 알면
 * 되는 정보의 것이다. 첫 글은 "지역이 필요한 일은 먼저 묻지 말고 서울 기준으로"였고, 그 글대로면
 * 위치를 모르는 사람의 "근처 약국 알려줘"도 묻지 않고 서울 전체에서 찾는다 — 서울 어딘가의
 * 약국은 대부분의 사람에게 이십 킬로미터 밖이다(PR 91 리뷰). 그래서 가까운 곳을 찾는 일은 전처럼
 * 한 번 묻는다.
 *
 * 들은 답은 그 일에만 쓴다. 한동안 이 글은 "들은 곳을 remember의 place로 저장한 다음"이었고,
 * 바로 뒤 문장은 잠깐 있는 곳은 저장하지 않는다고 했다. 한 시간 강남역에 서 있는 사람은 어디
 * 사는지 말한 것이 아닌데, 여섯 번 중 여섯 번 "서울 강남구"가 저장됐다
 * (`nearby-answer-is-used-and-not-saved`) — 그 뒤의 "오늘 날씨 어때?"는 전부 강남 날씨가 된다.
 * 저장의 규칙은 하나다(`SAVE_WHAT_THEY_SAY`): 자기 곳이라고 말한 곳만.
 */
const ASK_WHERE_FOR_NEARBY =
  "'근처'·'가까운 곳'처럼 이 사람 주변을 알아야 하는 일은 서울로 짐작하지 말고 어디인지 한 번 여쭤보고, 들은 곳 기준으로 한다.";

/**
 * 위치가 있을 때 그것을 어떻게 쓰는지. 이름을 대야 사장님이 틀린 곳을 바로잡을 수 있다.
 *
 * "검색어에 넣는다"만으로는 모자랐다(2026-09-24 로컬 실측). 봇은 구글에 "서울 강남구 날씨"를
 * 검색했고, 구글이 VM의 주소를 막자 네이버 날씨 홈으로 갔다. 그 페이지는 VM의 현위치(제주시
 * 이도2동)를 그렸고, 봇은 그 숫자를 "서울 강남구 기준"이라고 답했다 — 이름은 맞고 날씨는 제주의
 * 것. 그래서 두 가지를 적는다: 곳 이름을 넣은 네이버 검색이라는 구체적인 길, 그리고 페이지가 그린
 * 지역을 보고 다르면 그 값을 버리라는 것.
 */
function useIt(place: string): string {
  return `${WEATHER_BY_TOOL}(인자 없이 부르면 이 곳 기준이다). 그 도구가 없을 때의 날씨와, 가까운 곳처럼 위치가 필요한 다른 일은 매번 이 곳 이름을 검색어에 넣어 새로 찾는다(예: 네이버 검색 '${place} 날씨'). 페이지에 적힌 지역 이름을 확인하고, 이 곳이 아니면 그 숫자는 전하지 않는다. 답할 때 어느 곳 기준인지 말한다.`;
}

/**
 * 위치 줄. 언제나 한 줄이 선다 — 모를 때도, 모른다는 것과 어떻게 알아내는지를 말해야 봇이 사이트의
 * 짐작으로 빈칸을 메우지 않는다.
 *
 * `holds.weatherTool`은 이번 실행이 날씨 도구를 쥐었는지다(`contextFactsFor`가 실행의 툴 이름에서
 * 읽는다). 쥐었다고 아는 실행에는 "그 도구가 없으면 검색어에 서울을 넣는다"를 싣지 않는다 — 키가
 * 있는 배포의 모든 턴 앞에 서 있던, 그 배포에서는 쓰일 일이 없는 문장이다. 모르면(툴 이름 없이
 * 지은 글) 싣는다: 없는 도구를 믿고 길을 지운 글보다 한 문장 긴 글이 낫다.
 */
export function placeText(
  person: PromptPerson | undefined,
  mode: PromptMode,
  holds: { weatherTool?: boolean } = {},
): string {
  const place = person?.place?.trim();
  const saving = mode === "chat" ? SAVE_WHAT_THEY_SAY : "";
  if (place) {
    return [
      `이 사람의 위치(가게나 주로 지내는 곳): ${place}. ${useIt(place)}`,
      saving,
      NOT_THE_SITES_GUESS,
    ]
      .filter(Boolean)
      .join(" ");
  }
  const at = person?.coordinates;
  if (at) {
    const numbers = `위도 ${at.latitude.toFixed(2)}, 경도 ${at.longitude.toFixed(2)}`;
    const near = person?.near?.trim();
    /*
     * 이름이 있으면 가까운 곳도 묻지 않고 그 이름으로 찾는다. 없으면(표에 없는 칸, 바다, 나라 밖)
     * 숫자만으로는 찾을 수 없으니 전처럼 동네를 한 번 묻는다.
     */
    /*
     * 부근은 한 번만. 표에 제 줄이 없는 칸은 이름이 이미 "서귀포시 부근"으로 온다(가장 가까운
     * 줄의 이름, `kma-places.ts`의 `nameOf`) — 거기에 한 번 더 붙여 "서귀포시 부근 부근"이라고
     * 적었었다(PR 91 리뷰).
     */
    const around = near && !near.endsWith("부근") ? `${near} 부근` : near;
    return [
      around
        ? `이 사람의 위치: ${around}(${numbers}, 이 사람 기기에서 받은 대략적인 값).`
        : `이 사람의 위치: ${numbers} 부근(이 사람 기기에서 받은 대략적인 값).`,
      `${WEATHER_BY_TOOL}(인자 없이 부르면 이 부근 기준이다).`,
      near
        ? "그 도구가 없을 때의 날씨와, 가까운 곳처럼 위치가 필요한 다른 일은 먼저 묻지 말고 이 곳 이름을 검색어에 넣어 찾고, 답할 때 어느 곳 기준인지 말한다."
        : "그 도구가 없을 때의 날씨와, 가까운 곳처럼 위치가 필요한 다른 일은 이 부근 기준으로 하고, 답할 때 어느 곳 기준인지 말한다.",
      !near && mode === "chat"
        ? "동네 이름이 꼭 필요한 일이면 한 번 여쭤본다."
        : "",
      saving,
      NOT_THE_SITES_GUESS,
    ]
      .filter(Boolean)
      .join(" ");
  }
  /*
   * 아무것도 모를 때: 서울. 날씨 도구는 인자 없이 부르면 서울 기준으로 답하고 결과에 그 사실을
   * 적는다(`placeSource: "fallback"`). 도구가 없는 배포에서는 검색어에 서울을 넣는다 — 곳 없이
   * 검색하면 페이지는 VM이 있는 곳을 그린다.
   *
   * "곳을 대지 않은 질문은 인자 없이"라고 적는 까닭. "(인자 없이 부르면 서울 기준이다)"만 적었을
   * 때 봇은 가끔 그 말을 호출에 옮겼다 — `get_weather({place: "서울"})`, 대화에서 열 번에 한 번,
   * 루틴에서 다섯 번에 두 번. 호출이 이름을 댄 곳의 답은 "아무도 고르지 않은 서울"로 표시되지
   * 않으므로(`placeSource: "named"`) 카드가 "위치를 아직 몰라요"라고 적지 못한다.
   *
   * 그리고 "이 사람이 댄 곳은 그대로"까지. 한동안 이 글은 "place에 서울을 넣지 않는다"였는데,
   * 언제 그런지가 없었다: 위치를 모르는 사람이 "서울 마포구 날씨 어때?"라고 물으면 마포구를
   * 넣어야 한다(PR 91 리뷰). 비워 두는 것은 곳을 대지 않은 질문일 때뿐이다.
   */
  const seoul = [
    `${WEATHER_BY_TOOL}(곳을 대지 않은 질문은 인자 없이 부른다 — 서울 기준으로 온다. 이 사람이 댄 곳은 그대로 place에 넣는다).`,
    holds.weatherTool
      ? ""
      : "그 도구가 없으면 검색어에 서울을 넣는다(예: 네이버 검색 '서울 날씨').",
  ]
    .filter(Boolean)
    .join(" ");
  return mode === "chat"
    ? `이 사람의 위치는 아직 모른다. 날씨처럼 어느 지역인지만 알면 되는 일은 먼저 묻지 말고 서울 기준으로 하고, 답할 때 서울 기준이라고 짧게 말한다. ${ASK_WHERE_FOR_NEARBY} ${seoul} ${SAVE_WHAT_THEY_SAY} ${NOT_THE_SITES_GUESS}`
    : `이 사람의 위치를 모른다. 날씨처럼 어느 지역인지만 알면 되는 일은 서울 기준으로 하고, 결과에 서울 기준이라고 적는다. 이 사람 주변을 알아야 하는 일은 위치를 몰라 하지 못했다고 적는다. ${seoul} ${NOT_THE_SITES_GUESS}`;
}
