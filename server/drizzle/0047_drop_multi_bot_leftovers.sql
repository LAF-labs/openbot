WHERE "thread_id" IN (
  SELECT "thread_id" FROM "channel_threads"
  WHERE "channel_id" IN (
    SELECT "channel_id" FROM "channel_agents" GROUP BY "channel_id" HAVING count(*) > 1
  )
);--> statement-breakpoint
